function appT(key, replacements) {
    const lang = window.CAD_APP?.locale || "pl";
    let val = (APP_I18N[lang] || APP_I18N.pl)[key] || APP_I18N.pl[key] || key;
    if (replacements) {
        Object.entries(replacements).forEach(([name, value]) => {
            val = val.replaceAll(`{${name}}`, value);
        });
    }
    return val;
}

function applyAppI18n() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.getAttribute("data-i18n");
        const val = appT(key);
        if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
            if (el.hasAttribute("data-i18n-placeholder")) el.placeholder = val;
        } else {
            el.textContent = val;
        }
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        el.placeholder = appT(el.getAttribute("data-i18n-placeholder"));
    });
    document.documentElement.lang = window.CAD_APP?.locale || "pl";
    window.dispatchEvent(new CustomEvent("cad:app-locale-change"));
}
