function appT(key, replacements) {
    const lang = window.CAD_APP?.locale || "pl";
    let val = (APP_I18N[lang] || APP_I18N.pl)[key] || APP_I18N.pl[key] || key;
    if (replacements) {
        Object.entries(replacements).forEach(([name, value]) => {
            val = val.replaceAll(`{${name}}`, value);
        });
    }
    return val;
}

const LANG_BTN_I18N = { pl: "langBtnPl", nl: "langBtnNl", en: "langBtnEn" };
const RESERVED_I18N_KEYS = new Set(["pl", "nl", "en"]);

function isLangSwitcherElement(el) {
    return (
        el.classList.contains("lang-pill") ||
        el.classList.contains("currency-pill") ||
        !!el.closest(".app-lang-switch") ||
        !!el.closest(".app-currency-switch")
    );
}

function applyLangPills() {
    document.querySelectorAll(".lang-pill[data-locale]").forEach((btn) => {
        const code = btn.getAttribute("data-locale");
        const key = LANG_BTN_I18N[code];
        if (key) btn.setAttribute("aria-label", appT(key));
    });
}

function applyAppI18n() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
        if (isLangSwitcherElement(el)) return;
        const key = el.getAttribute("data-i18n");
        if (!key || RESERVED_I18N_KEYS.has(key)) return;
        const val = appT(key);
        if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
            if (el.hasAttribute("data-i18n-placeholder")) el.placeholder = val;
        } else if (el.childElementCount && el.querySelector("i, svg, img, button, a")) {
            const textTarget = el.querySelector(":scope > span[data-i18n-text]") || el.querySelector(":scope > span");
            if (textTarget && textTarget !== el) {
                textTarget.textContent = val;
            } else {
                el.textContent = val;
            }
        } else {
            el.textContent = val;
        }
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        if (isLangSwitcherElement(el)) return;
        el.placeholder = appT(el.getAttribute("data-i18n-placeholder"));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
        if (isLangSwitcherElement(el)) return;
        el.setAttribute("aria-label", appT(el.getAttribute("data-i18n-aria")));
    });
    applyLangPills();
    document.documentElement.lang = window.CAD_APP?.locale || "pl";
    window.dispatchEvent(new CustomEvent("cad:app-locale-change"));
}
